"""Run repository jobs on Kaggle's free GPU (T4) and fetch the results.

A "job" is a bash script in jobs/. `push` packs the repository's tracked
files into a zip, embeds it (base64) together with the job script into one
Python file, and submits that file as a private Kaggle script kernel with
GPU and internet enabled. On Kaggle the kernel unpacks the repo to
/kaggle/temp/repo, runs the job with REPO and OUT (= /kaggle/working/out)
set, and everything written to OUT becomes the kernel's output.

Authentication: the Kaggle SDK sends `Authorization: Bearer <token>`. In
our cloud environment the network proxy injects the real token, so the code
only ever sees the placeholder below. Elsewhere, set KAGGLE_API_TOKEN.

  export KAGGLE_USERNAME=<your kaggle username>
  python -m scripts.kaggle_jobs push   --job jobs/m1_acceptance.sh --slug wtt-m1-acceptance
  python -m scripts.kaggle_jobs status --ref $KAGGLE_USERNAME/wtt-m1-acceptance
  python -m scripts.kaggle_jobs wait   --ref $KAGGLE_USERNAME/wtt-m1-acceptance
  python -m scripts.kaggle_jobs fetch  --ref $KAGGLE_USERNAME/wtt-m1-acceptance --dest kaggle_out/m1
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import subprocess
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER_TOKEN = "proxy-injected"
DONE = {"COMPLETE", "ERROR", "CANCEL_ACKNOWLEDGED"}

KERNEL_TEMPLATE = r'''# Auto-generated by scripts/kaggle_jobs.py -- do not edit by hand.
import base64, io, os, subprocess, sys, zipfile
REPO = "/kaggle/temp/repo"
OUT = "/kaggle/working/out"
os.makedirs(REPO, exist_ok=True)
os.makedirs(OUT, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(REPO)
with open(os.path.join(REPO, "_job.sh"), "w") as f:
    f.write(JOB)
env = dict(os.environ, REPO=REPO, OUT=OUT, PYTHONUNBUFFERED="1")
with open(os.path.join(OUT, "job.log"), "w") as log:
    p = subprocess.Popen(["bash", "-o", "pipefail", os.path.join(REPO, "_job.sh")], cwd=REPO, env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        sys.stdout.write(line)
        log.write(line)
    code = p.wait()
with open(os.path.join(OUT, "exit_code.txt"), "w") as f:
    f.write(str(code))
print("job exit code", code)
'''


def repo_zip(root: Path = REPO_ROOT) -> bytes:
    """Zip of tracked + untracked-but-not-ignored files (the working tree as git sees it)."""
    names = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=root, capture_output=True,
                           text=True, check=True).stdout.split("\n")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for n in filter(None, names):
            p = root / n
            if p.is_file():
                zf.write(p, n)
    return buf.getvalue()


def kernel_source(job_text: str, root: Path = REPO_ROOT) -> str:
    payload = base64.b64encode(repo_zip(root)).decode()
    return f"PAYLOAD = {payload!r}\nJOB = {job_text!r}\n" + KERNEL_TEMPLATE


def client():
    from kagglesdk import KaggleClient

    return KaggleClient(api_token=os.environ.get("KAGGLE_API_TOKEN", PLACEHOLDER_TOKEN))


def default_user() -> str | None:
    return os.environ.get("KAGGLE_USERNAME")


def push(job: Path, slug: str, title: str | None = None, gpu: bool = True, internet: bool = True,
         timeout_s: int | None = None, user: str | None = None, kernel_sources: list[str] | None = None) -> dict:
    """Submit a job. kernel_sources: earlier kernels ("user/slug") whose outputs are mounted read-only
    under /kaggle/input/<slug>/ (how later jobs reuse the clean bank)."""
    from kagglesdk.kernels.types.kernels_api_service import ApiSaveKernelRequest

    req = ApiSaveKernelRequest()
    u, sl = _split(slug, user or default_user())
    req.slug = f"{u}/{sl}"
    req.new_title = title or slug
    req.text = kernel_source(job.read_text())
    req.language = "python"
    req.kernel_type = "script"
    req.is_private = True
    req.enable_gpu = gpu
    req.enable_internet = internet
    if gpu:
        req.machine_shape = "NvidiaTeslaT4"
    if timeout_s:
        req.session_timeout_seconds = int(timeout_s)
    if kernel_sources:
        req.kernel_data_sources = list(kernel_sources)
    with client() as k:
        resp = k.kernels.kernels_api_client.save_kernel(req)
    out = {"ref": resp.ref, "url": resp.url, "version": resp.version_number, "error": resp.error}
    if resp.error:
        raise RuntimeError(f"Kaggle refused the kernel: {resp.error}")
    return out


def _split(ref_or_slug: str, user: str | None) -> tuple[str, str]:
    if "/" in ref_or_slug:
        u, s = ref_or_slug.split("/", 1)
        return u, s
    user = user or default_user()
    if not user:
        raise ValueError("pass --user, set KAGGLE_USERNAME, or give a full ref user/slug")
    return user, ref_or_slug


def status(ref: str, user: str | None = None) -> dict:
    from kagglesdk.kernels.types.kernels_api_service import ApiGetKernelSessionStatusRequest

    u, s = _split(ref, user)
    req = ApiGetKernelSessionStatusRequest()
    req.user_name, req.kernel_slug = u, s
    with client() as k:
        resp = k.kernels.kernels_api_client.get_kernel_session_status(req)
    name = resp.status.name if hasattr(resp.status, "name") else str(resp.status)
    return {"status": name, "failure_message": resp.failure_message}


def wait(ref: str, user: str | None = None, poll_s: int = 60, max_s: int = 6 * 3600) -> dict:
    t0 = time.time()
    while True:
        st = status(ref, user)
        print(f"[kaggle] {ref}: {st['status']} ({int(time.time() - t0)} s)", flush=True)
        if st["status"] in DONE or time.time() - t0 > max_s:
            return st
        time.sleep(poll_s)


def fetch(ref: str, dest: Path, user: str | None = None) -> list[str]:
    """Download every output file (and the kernel log) into dest."""
    from kagglesdk.kernels.types.kernels_api_service import ApiListKernelSessionOutputRequest

    u, s = _split(ref, user)
    dest.mkdir(parents=True, exist_ok=True)
    got, token = [], None
    with client() as k:
        while True:
            req = ApiListKernelSessionOutputRequest()
            req.user_name, req.kernel_slug = u, s
            req.page_size = 100
            if token:
                req.page_token = token
            resp = k.kernels.kernels_api_client.list_kernel_session_output(req)
            if resp.log:
                (dest / "kernel_log.json").write_text(resp.log)
            for f in resp.files or []:
                target = dest / f.file_name
                target.parent.mkdir(parents=True, exist_ok=True)
                with urllib.request.urlopen(f.url) as r, open(target, "wb") as w:
                    w.write(r.read())
                got.append(f.file_name)
            token = resp.next_page_token
            if not token:
                break
    return got


def delete(ref: str, user: str | None = None) -> None:
    """Delete a kernel (stops it if running). Its code is regenerated from the repo, so nothing is lost."""
    from kagglesdk.kernels.types.kernels_api_service import ApiDeleteKernelRequest

    u, s = _split(ref, user)
    req = ApiDeleteKernelRequest()
    req.user_name, req.kernel_slug = u, s
    with client() as k:
        k.kernels.kernels_api_client.delete_kernel(req)


def main() -> None:
    ap = argparse.ArgumentParser(description="Kaggle GPU jobs")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("--job", required=True, type=Path)
    p.add_argument("--slug", required=True)
    p.add_argument("--title")
    p.add_argument("--no-gpu", action="store_true")
    p.add_argument("--timeout-s", type=int)
    p.add_argument("--user", help="Kaggle username (default: $KAGGLE_USERNAME)")
    p.add_argument("--kernel-source", action="append", default=[], help="user/slug of an earlier job to mount")
    for name in ("status", "wait", "fetch", "delete"):
        s = sub.add_parser(name)
        s.add_argument("--ref", required=True, help="user/slug")
        if name == "fetch":
            s.add_argument("--dest", required=True, type=Path)
        if name == "wait":
            s.add_argument("--poll-s", type=int, default=60)
    args = ap.parse_args()
    if args.cmd == "push":
        print(json.dumps(push(args.job, args.slug, args.title, gpu=not args.no_gpu,
                                     timeout_s=args.timeout_s, user=args.user,
                                     kernel_sources=args.kernel_source or None), indent=2))
    elif args.cmd == "status":
        print(json.dumps(status(args.ref), indent=2))
    elif args.cmd == "wait":
        st = wait(args.ref, poll_s=args.poll_s)
        print(json.dumps(st, indent=2))
        sys.exit(0 if st["status"] == "COMPLETE" else 1)
    elif args.cmd == "delete":
        delete(args.ref)
        print(f"[kaggle] deleted {args.ref}")
    else:
        files = fetch(args.ref, args.dest)
        print(f"[kaggle] downloaded {len(files)} files to {args.dest}")


if __name__ == "__main__":
    main()
